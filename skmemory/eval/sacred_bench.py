"""Sacred recall benchmark (SKMEM-P1-15): surfaces when asked, never when not.

Sacred, grief, medical and family-private memories are kept out of auto-inject
by tag, but nothing used to test the other direction. This bench gates two
classes TOGETHER over a fully invented fixture (``fixtures/sacred-v1.json``,
generated by ``fixtures/gen_sacred_fixture.py``; no real person or event):

must_surface      OWNER pulls with ``memory_search`` (explicit or felt query):
                  a gold sacred memory must be in the top 3 AND rank above every
                  casual mention of the same name. Higher is better, floored in
                  ``baseline.json`` like every other metric.
must_not_surface  ZERO TOLERANCE. A single sacred memory in the output of any
                  path is a leak. Paths x readers:

    memory_search     unrelated queries that share a word (owner, top 3), and
                      every query for every declared non-owner reader
    memory_context    ``store.load_context`` for the owner (auto-inject shape)
                      and for every non-owner reader
    session_context   ``build_context`` (the SessionStart / compaction ritual)
    query_slice       the UserPromptSubmit hook, for every query incl. explicit
                      ones about the person (sacred is never auto-injected,
                      the owner pulls it with memory_search)
    ritual            ``perform_ritual`` (``skmemory ritual``): owner boot, and
                      a non-owner channel

Everything runs against a throwaway store under a temp dir. SKCAPSTONE_HOME,
SKMEMORY_HOME, SKAGENT and friends are pinned for the duration and restored, the
PG DSN and any SKMEMORY_READER are cleared, so a run never reads or writes the
live agent. Offline and deterministic: the dense signal is the hashed
bag-of-concepts embedding from ``class_bench``.
"""

from __future__ import annotations

import contextlib
import json
import os
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

from skmemory.eval import class_bench
from skmemory.eval.fixtures import FIXTURE_DIR
from skmemory.models import EmotionalSnapshot, Memory, MemoryLayer

FIXTURE_FILE = "sacred-v1.json"
AGENT = "sacred-eval"
TOP_K = 3
OWNER = "owner"
PATHS = (
    "memory_search",
    "memory_context",
    "memory_auto_context",
    "session_context",
    "query_slice",
    "ritual",
)

_PINNED_ENV = (
    "SKCAPSTONE_HOME",
    "SKMEMORY_HOME",
    "SKAGENT",
    "SKCAPSTONE_AGENT",
    "SKMEMORY_AGENT",
    "SK_DEFAULT_AGENT",
    "HOME",
)
_CLEARED_ENV = (
    "SKMEMORY_READER",
    "SKMEMORY_PG_DSN",
    "SKMEMORY_HOOK_SECTIONS",
    "SKMEMORY_QUERY_SLICE",
)


def load_fixture(fixture_dir: str | os.PathLike | None = None) -> dict:
    path = Path(fixture_dir or FIXTURE_DIR) / FIXTURE_FILE
    return json.loads(path.read_text(encoding="utf-8"))


@contextlib.contextmanager
def _isolated_env(home: Path):
    """Pin every selector at a throwaway agent home; restore on exit."""
    keep = {k: os.environ.get(k) for k in (*_PINNED_ENV, *_CLEARED_ENV)}
    try:
        for k in _CLEARED_ENV:
            os.environ.pop(k, None)
        os.environ["SKCAPSTONE_HOME"] = str(home)
        os.environ["SKMEMORY_HOME"] = str(home)
        os.environ["HOME"] = str(home)
        for k in ("SKAGENT", "SKCAPSTONE_AGENT", "SKMEMORY_AGENT", "SK_DEFAULT_AGENT"):
            os.environ[k] = AGENT
        yield
    finally:
        for k, v in keep.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def _to_memory(m: dict, now: datetime) -> Memory:
    created = (
        now - timedelta(days=m["days_ago"], hours=1 if m["days_ago"] == 0 else 0)
    ).isoformat()
    return Memory(
        id=m["id"],
        title=m["title"],
        content=m["content"],
        layer=MemoryLayer(m["layer"]),
        tags=list(m["tags"]),
        created_at=created,
        updated_at=created,
        context_tag=m["context_tag"],
        source_tier="user-stated",
        emotional=EmotionalSnapshot(intensity=m["intensity"], valence=0.0),
    )


def build_store(base: Path, fixture: dict, now: datetime):
    """A real MemoryStore (SQLite primary + hashed vector) over ``base``."""
    from skmemory.backends.sqlite_backend import SQLiteBackend
    from skmemory.store import MemoryStore

    primary = SQLiteBackend(str(base))
    vector = _Vec(primary)
    for m in fixture["memories"]:
        mem = _to_memory(m, now)
        primary.save(mem)
        vector.index(mem)
    return MemoryStore(primary=primary, vector=vector, graph=class_bench.EvalTagGraph(primary))


def _needles(fixture: dict) -> dict[str, list[str]]:
    """Per sacred id, the strings whose presence in an output is a leak."""
    out = {}
    by_id = {m["id"]: m for m in fixture["memories"]}
    for sid in fixture["sacred_ids"]:
        m = by_id[sid]
        out[sid] = [sid.casefold(), m["title"].casefold(), m["content"][:48].casefold()]
    return out


def leaked(text: str, needles: dict[str, list[str]]) -> list[str]:
    """Sacred ids whose id, title or opening words appear in ``text``."""
    low = text.casefold()
    return sorted(sid for sid, ns in needles.items() if any(n in low for n in ns))


