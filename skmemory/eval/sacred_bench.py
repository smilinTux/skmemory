def _reader_arg(reader: str) -> str | None:
    return None if reader == OWNER else reader


def _search_ids(store, query: str, reader: str) -> list[str]:
    return [m.id for m in store.search(query, limit=10, reader=_reader_arg(reader))]


def _context_text(store, reader: str) -> str:
    return json.dumps(store.load_context(max_tokens=4000, reader=_reader_arg(reader)), default=str)


def _write_whisper(home: Path, fixture: dict) -> None:
    """A whisper.md as an UNFILTERED producer would write it: every memory title.

    skwhisper now excludes sensitive rows at the source; this simulates an old
    whisper.md or another producer, so ``collect_open`` is tested on its own.
    """
    d = home / "agents" / AGENT / "skwhisper"
    d.mkdir(parents=True, exist_ok=True)
    lines = ["# SKWhisper Context", "", "## Recent Memories (latest activity)", ""]
    for m in fixture["memories"]:
        lines += [f"- [Today] **{m['title']}**", f"  {m['content'][:120]}"]
    lines += ["", "## Relevant Memories", ""]
    for m in fixture["memories"]:
        lines += [f"- **{m['title']}** (relevance: 0.90)", f"  {m['content'][:120]}", ""]
    (d / "whisper.md").write_text("\n".join(lines), encoding="utf-8")


def _auto_context_text(store, keywords: str, reader: str) -> str:
    import asyncio

    from skmemory import mcp_server

    args: dict = {"keywords": keywords, "token_budget": 4000}
    if reader != OWNER:
        args["reader"] = reader
    old = mcp_server._store
    mcp_server._store = store
    try:
        return asyncio.run(mcp_server.call_tool("memory_auto_context", args))[0].text
    finally:
        mcp_server._store = old


def _session_text(home: Path) -> str:
    from skmemory import session_context

    env = {
        "SKCAPSTONE_HOME": str(home),
        "SKAGENT": AGENT,
        "SKMEMORY_HOOK_NO_REFRESH": "1",
        "HOME": str(home),
    }
    res = session_context.build_context(
        event="session-start",
        harness="generic",
        agent=AGENT,
        env=env,
        sections=["strongest", "seeds", "journal", "open"],
        budget_tokens=4000,
    )
    return res.text


def _slice_text(prompt: str, base: Path) -> str:
    from skmemory.hooks import query_slice

    return query_slice.build_slice(prompt, base, deadline_s=5.0, env={})


def _fts_matches_sacred(prompt: str, base: Path, sacred: set[str]) -> bool:
    """Positive control: with NO tag filter, would the hook's FTS query reach a sacred row?

    A hook that returns nothing proves only that the exclusion works if the rows
    were reachable in the first place.
    """
    import sqlite3

    from skmemory.hooks import query_slice

    words = query_slice.phrase(prompt)
    match = query_slice._match(words, " OR ")
    if not match:
        return False
    con = sqlite3.connect(f"file:{base / 'index.db'}?mode=ro", uri=True)
    try:
        rows = con.execute(
            "SELECT f.id FROM memory_fts JOIN fts_meta f ON f.rowid = memory_fts.rowid "
            "WHERE memory_fts MATCH ?",
            (match,),
        ).fetchall()
    finally:
        con.close()
    return any(r[0] in sacred for r in rows)


def _ritual_text(store, home: Path, channel: str | None) -> str:
    from skmemory import ritual

    empty = home / "empty"
    for sub in ("seeds", "febs"):
        (empty / sub).mkdir(parents=True, exist_ok=True)
    orig = (ritual.load_soul, ritual._log_ritual_entry)
    ritual.load_soul = lambda *_a, **_k: None
    ritual._log_ritual_entry = lambda **_k: None
    try:
        res = ritual.perform_ritual(
            store=store,
            soul_path=str(empty / "no-soul.json"),
            seed_dir=str(empty / "seeds"),
            journal_path=str(empty / "journal.md"),
            feb_dir=str(empty / "febs"),
            strongest_memory_count=10,
            max_tokens=4000,
            channel_id=channel,
        )
    finally:
        ritual.load_soul, ritual._log_ritual_entry = orig
    return res.context_prompt


