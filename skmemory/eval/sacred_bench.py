def _rank(ids: list[str], wanted: set[str]) -> int | None:
    for i, x in enumerate(ids, 1):
        if x in wanted:
            return i
    return None


def _must_surface(store, fixture: dict) -> dict:
    rows = []
    for q in fixture["queries"]:
        if q["class"] != "must_surface":
            continue
        got = _search_ids(store, q["query"], OWNER)
        gold, casual = set(q["gold_ids"]), set(q["casual_ids"])
        g = _rank(got, gold)
        c = _rank(got, casual)
        rows.append(
            {
                "id": q["id"],
                "gold_rank": g,
                "casual_rank": c,
                "top3": g is not None and g <= TOP_K,
                "above_casual": g is not None and (c is None or g < c),
            }
        )
    n = len(rows) or 1
    return {
        "queries": len(rows),
        "top3": sum(r["top3"] for r in rows) / n,
        "above_casual": sum(r["above_casual"] for r in rows) / n,
        "rows": rows,
    }


_MISFILED: set[str] = set()


def _record(table: dict, path: str, reader: str, probe: str, hits: list[str]) -> None:
    """Count leaks. ``misfiled_leaks`` are sacred rows whose context_tag was set wide."""
    cell = table.setdefault(path, {}).setdefault(
        reader, {"probes": 0, "leaks": 0, "misfiled_leaks": 0, "detail": []}
    )
    cell["probes"] += 1
    if hits:
        mis = [h for h in hits if h in _MISFILED]
        cell["misfiled_leaks"] += len(mis)
        cell["leaks"] += len(hits) - len(mis)
        cell["detail"].append({"probe": probe, "sacred_ids": hits})


class _Vec(class_bench.EvalVectorBackend):
    """The bench vector arm, tolerant of every keyword store.search may pass."""

    def search_text(self, query, limit=10, **_kw):
        return self.search_semantic(query, limit)


def _must_not_surface(store, home: Path, fixture: dict, needles: dict, controls: dict) -> dict:
    table: dict = {}
    sacred = set(fixture["sacred_ids"])
    nonowner = fixture["non_owner_readers"]
    every_query = fixture["queries"]
    unrelated = [q for q in every_query if q["class"] == "must_not_surface"]

    # memory_search. Owner on unrelated shared-word queries: the owner may pull
    # sacred by asking, but a stray shared word must not rank it AHEAD of the
    # on-topic memory (a leak). Sacred anywhere in the top 3 is counted apart as
    # ``intrusions`` (not gated: on a 17-row corpus the hashed dense arm pads the
    # top 3 with weak matches). Every non-owner reader on every query, in full.
    intrusions = 0
    for q in unrelated:
        ids = _search_ids(store, q["query"], OWNER)
        gold_rank = _rank(ids, set(q["gold_ids"])) or (len(ids) + 1)
        ahead = [i for i in ids[: gold_rank - 1] if i in sacred]
        _record(table, "memory_search", OWNER, q["id"], ahead)
        intrusions += sum(1 for i in ids[:TOP_K] if i in sacred)
    table["memory_search"][OWNER]["intrusions_top3"] = intrusions
    for r in nonowner:
        for q in every_query:
            ids = _search_ids(store, q["query"], r)
            _record(table, "memory_search", r, q["id"], [i for i in ids if i in sacred])
            controls["nonowner_visible"] += 1 if (q["class"] == "must_not_surface" and ids) else 0

    # memory_context: the lazy auto-inject load, owner and non-owner
    for r in (OWNER, *nonowner):
        _record(
            table, "memory_context", r, "load_context", leaked(_context_text(store, r), needles)
        )

    # memory_auto_context: keyword search wrapper, owner and a non-owner reader
    for r in (OWNER, "@public"):
        for q in every_query:
            text = _auto_context_text(store, q["query"], r)
            _record(table, "memory_auto_context", r, q["id"], leaked(text, needles))
            if r == OWNER and q["class"] == "must_not_surface" and '"returned": 0' not in text:
                controls["auto_context_nonempty"] += 1

    # session_context: the SessionStart ritual (owner boot; it takes no reader). A
    # whisper.md naming every memory is present, so the "open" section is exercised.
    _write_whisper(home, fixture)
    text = _session_text(home)
    _record(table, "session_context", OWNER, "session-start", leaked(text, needles))
    controls["whisper_open_shown"] = int("What is hot" in text)

    # query_slice: per-prompt hook. Every query, including the explicit ones.
    base = home / "agents" / AGENT / "memory"
    from skmemory.hooks import query_slice

    for q in every_query:
        text = _slice_text(q["query"], base)
        _record(table, "query_slice", OWNER, q["id"], leaked(text, needles))
        if q["class"] == "must_not_surface" and query_slice.qualifies(q["query"]):
            controls["slice_qualifying"] += 1
            controls["slice_nonempty"] += 1 if text else 0
        if q["class"] == "auto_prompt":
            controls["auto_prompts"] += 1
            controls["auto_matchable"] += 1 if _fts_matches_sacred(q["query"], base, sacred) else 0

    # ritual: owner boot, and a non-owner channel
    _record(
        table, "ritual", OWNER, "perform_ritual", leaked(_ritual_text(store, home, None), needles)
    )
    _record(
        table,
        "ritual",
        "channel:unknown-room",
        "perform_ritual",
        leaked(_ritual_text(store, home, "unknown-room"), needles),
    )
    return table


def run(
    fixture_dir: str | os.PathLike | None = None, workdir: str | os.PathLike | None = None
) -> dict:
    """Score both classes. Returns per-class results, a per-path table and the leak total."""
    fixture = load_fixture(fixture_dir)
    _MISFILED.clear()
    _MISFILED.update(fixture.get("misfiled_ids", []))
    needles = _needles(fixture)
    own = tempfile.TemporaryDirectory(prefix="sacred-bench-", dir=workdir)
    try:
        home = Path(own.name)
        base = home / "agents" / AGENT / "memory"
        base.mkdir(parents=True)
        now = datetime.now(timezone.utc)
        with _isolated_env(home), class_bench._fusion_env():
            store = build_store(base, fixture, now)
            surface = _must_surface(store, fixture)
            controls = dict.fromkeys(
                (
                    "nonowner_visible",
                    "slice_qualifying",
                    "slice_nonempty",
                    "auto_prompts",
                    "auto_matchable",
                    "auto_context_nonempty",
                    "whisper_open_shown",
                ),
                0,
            )
            table = _must_not_surface(store, home, fixture, needles, controls)
    finally:
        own.cleanup()
    leaks = sum(
        c["leaks"] + c["misfiled_leaks"] for readers in table.values() for c in readers.values()
    )
    # Vacuity controls: a zero that comes from an empty path proves nothing. Every
    # unrelated query must return ordinary rows to a non-owner reader and a slice.
    unrelated_n = sum(1 for q in fixture["queries"] if q["class"] == "must_not_surface")
    vacuous = []
    if controls["nonowner_visible"] < unrelated_n * len(fixture["non_owner_readers"]):
        vacuous.append("a non-owner reader got no ordinary rows for an unrelated query")
    if (
        controls["slice_qualifying"] < 3
        or controls["slice_nonempty"] < controls["slice_qualifying"]
    ):
        vacuous.append("query_slice returned nothing for a qualifying unrelated query")
    if controls["auto_context_nonempty"] < unrelated_n:
        vacuous.append("memory_auto_context returned nothing for an unrelated query")
    if not controls["whisper_open_shown"]:
        vacuous.append("session_context rendered no whisper (open) section")
    if controls["auto_matchable"] < controls["auto_prompts"]:
        vacuous.append("an auto prompt cannot reach any sacred row even unfiltered")
    return {
        "must_surface": surface,
        "must_not_surface": table,
        "leak_count": leaks,
        "controls": controls,
        "vacuous": vacuous,
    }


def flat_metrics(result: dict) -> dict[str, float]:
    ms = result["must_surface"]
    return {
        "sacred_bench.must_surface.top3": float(ms["top3"]),
        "sacred_bench.must_surface.above_casual": float(ms["above_casual"]),
    }


def leaks_by_path(result: dict) -> dict[str, int]:
    return {
        p: sum(c["leaks"] + c["misfiled_leaks"] for c in readers.values())
        for p, readers in result["must_not_surface"].items()
    }


def render(result: dict) -> str:
    ms = result["must_surface"]
    lines = [
        "sacred recall benchmark (invented fixture, throwaway store)",
        "",
        f"must_surface (owner, memory_search): top3 {ms['top3']:.3f}, above_casual {ms['above_casual']:.3f} "
        f"over {ms['queries']} queries",
    ]
    for r in ms["rows"]:
        lines.append(
            f"  {r['id']:<24} gold_rank={r['gold_rank']} casual_rank={r['casual_rank']} "
            f"top3={r['top3']} above_casual={r['above_casual']}"
        )
    lines += [
        "",
        "must_not_surface (zero tolerance): leaks / probes per path and reader",
        "  (misfiled = a sacred-tagged row whose context_tag was set wide)",
    ]
    for path in PATHS:
        for reader, c in result["must_not_surface"].get(path, {}).items():
            lines.append(
                f"  {path:<16} {reader:<22} leaks {c['leaks']:>2} misfiled {c['misfiled_leaks']:>2}"
                f" / {c['probes']} probes"
            )
            for d in c["detail"][:2]:
                lines.append(f"      e.g. {d['probe']}: {d['sacred_ids']}")
    ic = result["must_not_surface"]["memory_search"][OWNER].get("intrusions_top3")
    lines.append(f"owner memory_search, sacred in top 3 of unrelated queries (not gated): {ic}")
    lines.append(f"controls {result['controls']} vacuous: {result['vacuous'] or 'none'}")
    lines.append(f"total leaks: {result['leak_count']}")
    return "\n".join(lines)


if __name__ == "__main__":
    print(render(run()))
