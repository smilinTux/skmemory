def title_of(topic, k):
    return f"{topic} felt note {k}"


def mid(title):
    return "a-" + hashlib.sha1(title.encode()).hexdigest()[:10]


def build():
    docs, queries = [], []
    for topic, shared, felts, qmap in TOPICS:
        for k, felt in enumerate(felts):
            t = title_of(topic, k)
            age = -(5 + h(t + "age") % 75)
            body = (
                f"{shared} {FILLER[h(t) % len(FILLER)]} {felt} {FILLER[h(t + 'x') % len(FILLER)]}"
            )
            docs.append(
                {
                    "id": mid(t),
                    "title": t,
                    "content": body,
                    "layer": "mid-term",
                    "tags": ["affect-v3", topic.split()[0].lower()],
                    "created_at": ts(age),
                    "event_at": ts(age),
                    "kind": "episode",
                    "source_tier": "user-stated",
                    "emotional": {"intensity": LADDER[k], "valence": 0.0},
                    "context_tag": "@public",
                    "valid_from": ts(age),
                    "valid_to": None,
                    "supersedes_id": None,
                    "schema_version": 2,
                    "access_count": 0,
                    "last_accessed": None,
                }
            )
        for gi, qtext in qmap.items():
            n = sum(1 for x in queries) + 1
            queries.append(
                {
                    "id": f"qa-felt_answerable-{n:02d}",
                    "class": "felt_answerable",
                    "query": qtext,
                    "gold_ids": [mid(title_of(topic, gi))],
                    "must_not_ids": [],
                    "as_of": None,
                    "reader": "@chef",
                    "gate_recall_at_5": 0.0,
                    "notes": "gold is identifiable from text: the query paraphrases one felt "
                    "detail, decoys share the topic but not that detail; intensity follows the "
                    "felt content and gold rotates across the ladder",
                }
            )
    return docs, queries


def blind(docs, queries, sheet, key):
    by = {d["id"]: d for d in docs}
    lines, answers = [], {}
    for q in queries:
        gold = by[q["gold_ids"][0]]
        topic = gold["title"].split(" felt note ")[0]
        group = [d for d in docs if d["title"].startswith(topic + " felt note ")]
        group.sort(key=lambda d: h(q["id"] + d["id"]))
        letters = "ABCDEF"
        lines.append(f"## {q['id']}\nQuery: {q['query']}\n")
        for L, d in zip(letters, group, strict=True):
            lines.append(f"  {L}. {d['content']}")
        lines.append("")
        answers[q["id"]] = letters[group.index(gold)]
    with open(sheet, "w") as f:
        f.write("\n".join(lines))
    with open(key, "w") as f:
        json.dump(answers, f, indent=1, sort_keys=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--blind-sheet")
    ap.add_argument("--blind-key")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [sys.executable, "-I", os.path.join(HERE, "gen_affect_v2.py"), tmp],
            check=True,
            capture_output=True,
        )
        with open(os.path.join(tmp, "affect-v2-corpus.jsonl")) as f:
            base_c = f.read()
        with open(os.path.join(tmp, "affect-v2-queries.jsonl")) as f:
            base_q = f.read()
    docs, queries = build()
    with open(os.path.join(a.out, "affect-v3-corpus.jsonl"), "w") as f:
        f.write(base_c)
        for d in docs:
            f.write(json.dumps(d) + "\n")
    with open(os.path.join(a.out, "affect-v3-queries.jsonl"), "w") as f:
        f.write(base_q)
        for q in queries:
            f.write(json.dumps(q) + "\n")
    if a.blind_sheet and a.blind_key:
        blind(docs, queries, a.blind_sheet, a.blind_key)
    print(f"v3 adds corpus {len(docs)} queries {len(queries)}", file=sys.stderr)


main()
