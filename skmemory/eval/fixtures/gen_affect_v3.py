"""Deterministic generator for the affect-v3 eval fixture (SKMEM-P1-17).

Everything here is INVENTED. skmemory is a public repo: no text comes from any
real agent store, person, host or secret.

affect-v3 = affect-v2 (unchanged, generated by gen_affect_v2.py) plus ONE new class,
``felt_answerable``, written to fix the oracle in affect-v2 felt_peak. There the same
felt sentence appears verbatim in the gold and in all five decoys, so only intensity can
separate them: the class measures "can a weight express a signal", not retrieval.

felt_answerable removes that. Per topic group of six memories:
- the six share the topic sentence but each carries a DIFFERENT felt detail (who, where,
  what the body did), so a careful reader can tell which memory a felt description means;
- the query is a PARAPHRASE of exactly one felt detail (no verbatim felt sentence, no topic
  word), so the gold is identifiable from text alone;
- intensity follows the felt content (a sob is 0.95, boredom 0.15) but the gold rotates
  across the whole intensity ladder, so intensity is NOT a tie-break oracle: a rule that
  prefers big numbers is right about as often as wrong;
- created_at is a hash of the title, uncorrelated with gold, intensity or position.
Two queries per topic (different golds) give 20 queries; they share corpus so they are
not independent, which the report states.

Run:  python3 -I gen_affect_v3.py <outdir> [--blind-sheet SHEET --blind-key KEY]
Out:  affect-v3-corpus.jsonl  affect-v3-queries.jsonl
--blind-sheet writes the queries with their six candidate texts shuffled and gold hidden,
--blind-key the answers, for the human answerability check recorded in the PR.
"""

