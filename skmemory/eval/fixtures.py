"""Loaders and schema models for the vendored v1 eval fixtures.

The fixtures under ``skmemory/eval/fixtures/`` are synthetic and generated by
``gen_fixtures.py`` (regenerate, never hand-edit). They carry v2 fields
(``kind``, ``event_at``, ``valid_from``/``valid_to``, ``supersedes_id``,
``source_tier``, ``context_tag``) that ``skmemory.models.Memory`` does not have
yet, so these models are dedicated to the fixtures and deliberately do not
reuse ``Memory``. Every model forbids unknown fields, so a schema drift in a
fixture fails loudly at load time.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

FIXTURE_DIR = Path(__file__).parent / "fixtures"


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


class Emotional(_Strict):
    intensity: float
    valence: float


class CorpusMemory(_Strict):
    id: str
    title: str
    content: str
    layer: str
    tags: list[str]
    created_at: str
    event_at: str
    kind: str
    source_tier: str
    emotional: Emotional
    context_tag: str
    valid_from: str
    valid_to: str | None
    supersedes_id: str | None
    schema_version: int
    outcome: str | None = None


class Query(_Strict):
    id: str
    query_class: str = Field(alias="class")
    query: str
    gold_ids: list[str]
    must_not_ids: list[str]
    as_of: str | None
    reader: str
    gate_recall_at_5: float
    notes: str = ""


class Intention(_Strict):
    id: str
    kind: str
    title: str
    state: str
    created_at: str
    origin_session: str
    origin_memory_id: str | None
    channel: str
    # time intentions
    due_at: str | None = None
    snooze_until: str | None = None
    # event intentions
    trigger_terms: list[str] = Field(default_factory=list)
    scope: dict[str, str] = Field(default_factory=dict)
    cooldown_s: int | None = None
    max_fires: int | None = None
    fires: int | None = None
    last_fired_at: str | None = None
    expires_at: str | None = None
    expected_state_after_supersession_sweep: str | None = None


class IntentionTransition(_Strict):
    state: str
    event: str
    expected: str


class Prompt(_Strict):
    id: str
    text: str
    scope: dict[str, str]
    now: str
    expected_fire: list[str]


class OutcomeEvent(_Strict):
    skill: str
    version: str
    event: str
    at: str
    effect: str | None
    session: str


class ExpectedOutcome(_Strict):
    follow_rate: float
    net_effect_sign: str
    anti_pattern: bool
    rank: int
    flag: str | None = None


class OutcomesExpected(_Strict):
    half_life_days: float
    harm_weight: float
    as_of: str
    expected: dict[str, ExpectedOutcome]


class AsOfCheck(_Strict):
    as_of: str
    valid: list[str]


class SupersessionChain(_Strict):
    ids: list[str]
    as_of_checks: list[AsOfCheck]


class NonSupersessionEdge(_Strict):
    child_kind: str
    edge: str
    must_not_close_parent: bool


class ConflictCase(_Strict):
    new_fact: str
    existing: str
    expected_verdict: str
    expected_edge: str | None
    # True when only an LLM judge can reach expected_verdict (rules never say changes/unchanged
    # on their own); without an LLM the write resolves to extends.
    needs_llm: bool = False


class Supersession(_Strict):
    chains: list[SupersessionChain]
    non_supersession_edges: list[NonSupersessionEdge]
    write_time_conflict_cases: list[ConflictCase]


class DecayChannels(_Strict):
    fact_half_life_days: float
    gist_half_life_days: float
    affect_floor: float


class DecayItem(_Strict):
    id: str
    kind: str
    created_at: str
    access_count: int
    last_accessed: str | None
    intensity: float


class DecayExpectedOrder(_Strict):
    none: list[str]
    recency: list[str]
    reinforcement: list[str]
    affect_weighted: list[str]
    invariants: list[str]


class ReinforcementVector(_Strict):
    op: str
    before: dict[str, Any]
    after: dict[str, Any]
    note: str | None = None


class Decay(_Strict):
    as_of: str
    channels: DecayChannels
    items: list[DecayItem]
    formulas: dict[str, str]
    expected_scores: dict[str, dict[str, float]]
    expected_order: DecayExpectedOrder
    reinforcement_write_vectors: list[ReinforcementVector]


def _dir(base: Path | str | None) -> Path:
    return Path(base) if base is not None else FIXTURE_DIR


def _jsonl(path: Path) -> list[dict[str, Any]]:
    rows = []
    with path.open(encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            if line.strip():
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError as exc:
                    raise ValueError(f"{path.name}:{n}: {exc}") from exc
    return rows


def _json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def load_corpus(base: Path | str | None = None) -> list[CorpusMemory]:
    return [CorpusMemory(**r) for r in _jsonl(_dir(base) / "corpus-v1.jsonl")]


def load_queries(base: Path | str | None = None) -> list[Query]:
    return [Query(**r) for r in _jsonl(_dir(base) / "queries-v1.jsonl")]


def load_intentions(base: Path | str | None = None) -> list[Intention]:
    return [Intention(**r) for r in _jsonl(_dir(base) / "intentions-v1.jsonl")]


def load_intention_transitions(base: Path | str | None = None) -> list[IntentionTransition]:
    return [
        IntentionTransition(**r) for r in _jsonl(_dir(base) / "intention-transitions-v1.jsonl")
    ]


def load_prompts(base: Path | str | None = None) -> list[Prompt]:
    return [Prompt(**r) for r in _jsonl(_dir(base) / "prompts-v1.jsonl")]


def load_outcomes(base: Path | str | None = None) -> list[OutcomeEvent]:
    return [OutcomeEvent(**r) for r in _jsonl(_dir(base) / "outcomes-v1.jsonl")]


def load_outcomes_expected(base: Path | str | None = None) -> OutcomesExpected:
    return OutcomesExpected(**_json(_dir(base) / "outcomes-expected-v1.json"))


def load_supersession(base: Path | str | None = None) -> Supersession:
    return Supersession(**_json(_dir(base) / "supersession-v1.json"))


def load_decay(base: Path | str | None = None) -> Decay:
    return Decay(**_json(_dir(base) / "decay-v1.json"))
